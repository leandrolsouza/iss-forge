/**
 * Match scenes for the stadium and crowd previews.
 *
 * The match tilemaps are not in the ROM: the game builds them while the camera
 * scrolls (64 x 64 ring buffers at VRAM words $1000 = BG2 and $0000 = BG1; BG1 is
 * scrolled 16 px further than BG2 in both directions). These are rectangles of
 * both maps captured from savestates of the original game (CPU x CPU demo,
 * pitch type B, sunny), in BG2 cells:
 *   back  = BG2 (pitch, stands, wall, slanted wall behind the goal)
 *   front = BG1 (front rows of the crowd, goal net, photographers)
 * Each row is a list of map words (palette << 10 | tile, bit 13 = priority,
 * bits 14/15 = flips); "word*n" repeats a word n times, missing rows are empty.
 *
 * The characters come from the ROM: the load list 0x1006C (see pitchPreview.js)
 * plus `rawTiles` = [first char, file offset, count] of the uncompressed chars
 * the game swaps in while playing (crowd animation, goal net in perspective).
 * Only positions are stored here; pixels and colours always come from the ROM
 * and the editor. See research/match-palettes.md.
 */

